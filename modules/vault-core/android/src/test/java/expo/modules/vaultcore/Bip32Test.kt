  private fun addressAt(path: String): String {
    val seed = Bip39.mnemonicToSeed(CANONICAL_MNEMONIC, "")
    try {
      return Bip32.toChecksumAddress(Bip32.deriveAddressBytes(seed, Bip32.parseEthereumPath(path)))
    } finally {
      seed.fill(0)
    }
  }

  private fun assertVector(vector: OfficialVector) {
    val seed = vector.seedHex.hexToBytes()
    val chainCodes = ArrayList<ByteArray>()
    try {
      var node = Bip32.masterNode(seed)
      chainCodes.add(node.chainCode)
      var index = 0
      assertEquals("${vector.id} first chain", "m", vector.chains[0].path)
      assertChainSerialization(vector, vector.chains[0], node)

      while (index + 1 < vector.chains.size) {
        val parentPath = vector.chains[index].path
        val childPath = vector.chains[index + 1].path
        assertTrue(
          "${vector.id} chain must extend ${parentPath} (got ${childPath})",
          childPath.startsWith("${parentPath}/")
        )
        val segment = childPath.substring(parentPath.length + 1)
        val hardened = segment.endsWith("'")
        val value = segment.removeSuffix("'").toLong()
        val childNumber = if (hardened) (0x80000000L + value).toInt() else value.toInt()
        node = Bip32.deriveChild(node, childNumber)
        chainCodes.add(node.chainCode)
        assertChainSerialization(vector, vector.chains[index + 1], node)
        index += 1
      }
    } finally {
      seed.fill(0)
      for (chainCode in chainCodes) {
        chainCode.fill(0)
      }
    }
  }

  private fun assertChainSerialization(vector: OfficialVector, chain: OfficialChain, node: Bip32.Node) {
    assertEquals("${vector.id} ${chain.path} xprv", chain.xprv, serialize(node, private = true))
    assertEquals("${vector.id} ${chain.path} xpub", chain.xpub, serialize(node, private = false))
  }

  /** 78-byte extended-key layout + Base58Check (test-only formatting). */
  private fun serialize(node: Bip32.Node, private: Boolean): String {
    val payload = ByteArray(78)
    if (private) {
      payload[0] = 0x04
      payload[1] = 0x88.toByte()
      payload[2] = 0xAD.toByte()
      payload[3] = 0xE4.toByte()
    } else {
      payload[0] = 0x04
      payload[1] = 0x88.toByte()
      payload[2] = 0xB2.toByte()
      payload[3] = 0x1E
    }
    payload[4] = node.depth.toByte()
    payload[5] = (node.parentFingerprint ushr 24).toByte()
    payload[6] = (node.parentFingerprint ushr 16).toByte()
    payload[7] = (node.parentFingerprint ushr 8).toByte()
    payload[8] = node.parentFingerprint.toByte()
    payload[9] = (node.childNumber ushr 24).toByte()
    payload[10] = (node.childNumber ushr 16).toByte()
    payload[11] = (node.childNumber ushr 8).toByte()
    payload[12] = node.childNumber.toByte()
    System.arraycopy(node.chainCode, 0, payload, 13, 32)

    if (private) {
      payload[45] = 0
      writeSer256TestOnly(node.key, payload, 46)
    } else {
      val publicKey = Bip32.compressedPublicKey(node)
      try {
        System.arraycopy(publicKey, 0, payload, 45, 33)
      } finally {
        publicKey.fill(0)
      }
    }
    return base58Check(payload)
  }

  private fun writeSer256TestOnly(value: BigInteger, out: ByteArray, offset: Int) {
    val bytes = value.toByteArray()
    try {
      when {
        bytes.size == 33 && bytes[0].toInt() == 0 -> System.arraycopy(bytes, 1, out, offset, 32)
        bytes.size <= 32 -> System.arraycopy(bytes, 0, out, offset + (32 - bytes.size), bytes.size)
        else -> error("value does not fit in 32 bytes")
      }
    } finally {
      bytes.fill(0)
    }
  }

  private fun base58Check(payload: ByteArray): String {
    val first = sha256(payload)
    val second = sha256(first)
    val checksummed = ByteArray(payload.size + 4)
    System.arraycopy(payload, 0, checksummed, 0, payload.size)
    System.arraycopy(second, 0, checksummed, payload.size, 4)
    first.fill(0)
    second.fill(0)
    return base58Encode(checksummed)
  }

  private fun sha256(input: ByteArray): ByteArray {
    val digest = SHA256Digest()
    val out = ByteArray(32)
    digest.update(input, 0, input.size)
    digest.doFinal(out, 0)
    return out
  }

  private fun base58Encode(input: ByteArray): String {
    val alphabet = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
    var value = BigInteger(1, input)
    val encoded = StringBuilder()
    while (value.signum() > 0) {
      val quotientAndRemainder = value.divideAndRemainder(BigInteger.valueOf(58))
      encoded.append(alphabet[quotientAndRemainder[1].toInt()])
      value = quotientAndRemainder[0]
    }
    for (byte in input) {
      if (byte.toInt() != 0) break
      encoded.append('1')
    }
    return encoded.reverse().toString()
  }

  private fun String.hexToBytes(): ByteArray {
    val clean = removePrefix("0x")
    require(clean.length % 2 == 0) { "hex length must be even" }
    return ByteArray(clean.length / 2) { index ->
      clean.substring(index * 2, index * 2 + 2).toInt(16).toByte()
    }
  }

  private fun ByteArray.toHex(): String = joinToString(separator = "") { byte ->
    "%02x".format(byte.toInt() and 0xFF)
  }

